# Builds bdscrub_standalone.R: the whole package in one R file, for people who
# cannot install packages. Run from the package root:
#   source("tools/make_standalone.R")
# The file is written to the path in `standalone_out` (default: extras/).
#
# It contains the code of R/ (without the roxygen documentation) and the data
# (R/sysdata.rda and data/*.rda) written out with dput(). Non-ASCII characters
# are written as \u escapes, so the file is plain ASCII and sources the same
# way on every computer.

out_file <- if (exists("standalone_out")) standalone_out else "extras/bdscrub_standalone.R"
version <- read.dcf("DESCRIPTION", fields = "Version")[1, 1]

escape_line <- function(line) {
  if (!grepl("[^ -~\t]", line, perl = TRUE)) return(line)
  cp <- utf8ToInt(line)
  ch <- vapply(cp, function(i) if (i < 128L) intToUtf8(i) else sprintf("\\u%04x", i), "")
  paste(ch, collapse = "")
}

code_files <- setdiff(list.files("R", pattern = "[.]R$", full.names = TRUE),
                      c("R/bdscrub-package.R", "R/data.R"))
code <- unlist(lapply(code_files, function(f) {
  x <- readLines(f, encoding = "UTF-8", warn = FALSE)
  x <- x[!grepl("^#'", x)]
  c(paste0("# ---- ", basename(f), " ", strrep("-", 70 - nchar(basename(f)))), x, "")
}))
code <- code[!(code == "" & c(FALSE, head(code, -1) == ""))]  # no double blank lines

data_env <- new.env()
load("R/sysdata.rda", envir = data_env)
for (f in list.files("data", pattern = "[.]rda$", full.names = TRUE)) load(f, envir = data_env)
data_code <- unlist(lapply(sort(ls(data_env, all.names = TRUE)), function(nm) {
  c(paste0(nm, " <- ", paste(deparse(get(nm, data_env), control = c("keepNA", "keepInteger",
                                                                       "niceNames", "showAttributes")),
                             collapse = "\n")), "")
}))

header <- c(
  "# =============================================================================",
  paste0("# bdscrub ", version, " -- one-file version"),
  "# Authors: Ishtiaq Mahmud Fahim and Humaira Kashmi (MIT licence)",
  "# =============================================================================",
  "# The bdscrub package in one file, for computers where the package cannot be",
  "# installed. Use it with:",
  "#     source(\"bdscrub_standalone.R\")",
  "# It defines the same eleven functions as the package:",
  "#     bd_phone()  bd_amount()  bd_number()  bd_taka()  bd_digits()",
  "#     bd_place()  bd_address() bd_missing() bd_squish() bd_check()  bd_clean()",
  "# and the data sets bd_districts, bd_divisions, bd_thanas,",
  "# bd_postcodes, bd_phone_prefixes and bd_na_words.",
  "# The documentation (arguments, examples) is in the package README and help",
  "# pages. Generated by tools/make_standalone.R; do not edit by hand.",
  "# Needs R >= 4.1 and no other package (tibble is used when installed).",
  "# =============================================================================",
  ""
)
lines <- c(header, "# ---- data ------------------------------------------------------------------", "", data_code, code,
           paste0("message(\"bdscrub ", version, " (one-file version) loaded.\")"))
lines <- vapply(enc2utf8(lines), escape_line, "", USE.NAMES = FALSE)
writeLines(lines, out_file, useBytes = TRUE)
cat("written:", out_file, "(", length(lines), "lines )\n")
